"""Fixed-budget high-frequency Hankel experiment.

Author
------
Shelvean Kapita
Department of Mathematics, Texas A&M University

Date
----
August 2026

Purpose
-------
The experiment keeps the mesh and the number of local plane waves fixed while
increasing the wavenumber.  A five-ray fan is centered around an elementwise
direction field and is polished by simple residual-decreasing angular trials.
The result is compared with five uniformly distributed directions on the same
mesh.  Thus both spaces have the same nominal number of Trefftz coefficients.

This is a stress test, not an asymptotic convergence experiment.  It shows how
far direction adaptation can delay the need for mesh refinement or further
angular enrichment when the approximation budget is held fixed.

Run
---

    python -m experiments.experiment_high_frequency_hankel

The script writes ``results/high_frequency_hankel.csv``.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd
from scipy.special import hankel1

from core.direction_adaptive import (
    PWDGDictionary,
    graph_data,
    l2_error,
    physical_skeleton_residual,
    q_real,
    uniform_dictionary,
)
from core.pwdg import square_mesh

__author__ = "Shelvean Kapita"
__date__ = "August 2026"

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results"
RESULTS.mkdir(exist_ok=True)

SOURCE = np.array([-1.6, 0.3])
WAVENUMBERS = (8, 16, 24, 32, 40)
NUMBER_OF_RAYS = 5


class OutgoingHankel:
    """Outgoing cylindrical wave generated by a source outside the square."""

    def __init__(self, k:
        float) -> None:
        self.k = float(k)
        self.source = SOURCE.copy()

    def wavenumber(self, y):
        return np.full(np.asarray(y).shape, self.k, dtype=float)

    def __call__(self, x, y):
        radius = np.hypot(
            np.asarray(x) - self.source[0],
            np.asarray(y) - self.source[1],
        )
        return hankel1(0, self.k * radius)


def solve_fan(k:
    float, centers, half_width: float, nq: int = 16):
    """Solve with an equally spaced five-ray fan on each element."""
    exact = OutgoingHankel(k)
    fan_coordinates = np.linspace(-1.0, 1.0, NUMBER_OF_RAYS)
    dictionaries = [
        np.array(
            [q_real(k, centers[e] + half_width * z) for z in fan_coordinates]
        )
        for e in range(len(centers))
    ]
    state = PWDGDictionary(2, exact, dictionaries, nq=nq)
    state.solve()
    return state


def objective(state) -> float:
    """Squared physical skeleton residual."""
    return physical_skeleton_residual(state) ** 2


def polish_fan(k, centers, half_width, step_degrees=5.0, max_sweeps=5):
    """Apply residual-decreasing center and fan-width trials.

    The routine is deliberately simple.  It is used only to construct the
    fixed-budget comparison in the paper and should not be confused with the
    more general MOVE/ENRICH/REFINE adaptive algorithm.
    """
    state = solve_fan(k, centers, half_width)
    current = objective(state)
    trials = 0
    step = np.deg2rad(step_degrees)

    for _ in range(max_sweeps):
        accepted = 0

        # First test two global changes of the fan half-width.
        for delta_half_width in (-step, step):
            trial_width = np.clip(
                half_width + delta_half_width,
                np.deg2rad(3.0),
                np.deg2rad(80.0),
            )
            trial_state = solve_fan(k, centers, trial_width, nq=12)
            trial_value = objective(trial_state)
            trials += 1
            if trial_value < current:
                current = trial_value
                state = trial_state
                half_width = trial_width
                accepted += 1

        # Then move each elementwise fan center independently.
        for element in range(len(centers)):
            best = (current, centers[element], state)
            for delta_angle in (-step, step):
                trial_centers = centers.copy()
                trial_centers[element] += delta_angle
                trial_state = solve_fan(k, trial_centers, half_width, nq=12)
                trial_value = objective(trial_state)
                trials += 1
                if trial_value < best[0]:
                    best = (trial_value, trial_centers[element], trial_state)

            if best[0] < current:
                current, centers[element], state = best
                accepted += 1

        if accepted == 0:
            break

    return centers, half_width, state, current, trials


def main() -> None:
    vertices, triangles = square_mesh(2)
    centroids = vertices[triangles].mean(axis=1)

    # The initial centers point radially away from the exterior source.  This is
    # used only to initialize the continuation; subsequent wavenumbers inherit
    # the adapted field from the previous solve.
    centers = np.arctan2(
        centroids[:, 1] - SOURCE[1],
        centroids[:, 0] - SOURCE[0],
    )
    half_width = np.deg2rad(25.0)

    rows = []
    for k in WAVENUMBERS:
        centers, half_width, adapted, residual, trials = polish_fan(
            k,
            centers,
            half_width,
        )
        adapted_graph = graph_data(adapted.A)

        exact = OutgoingHankel(k)
        uniform = PWDGDictionary(
            2,
            exact,
            uniform_dictionary(2, exact, NUMBER_OF_RAYS),
            nq=20,
        )
        uniform.solve()
        uniform_graph = graph_data(uniform.A)

        row = {
            "kappa": k,
            "adaptive_relative_L2": l2_error(adapted, nsub=14),
            "uniform_relative_L2": l2_error(uniform, nsub=14),
            "adaptive_skeleton_residual_squared": residual,
            "adaptive_graph_riesz_condition": adapted_graph["cond_gr"],
            "uniform_graph_riesz_condition": uniform_graph["cond_gr"],
            "fan_half_width_deg": np.degrees(half_width),
            "direction_trials": trials,
        }
        rows.append(row)
        print(row)

    output = RESULTS / "high_frequency_hankel.csv"
    pd.DataFrame(rows).to_csv(output, index=False)
    print(f"\nWrote {output}")


if __name__ == "__main__":
    main()
